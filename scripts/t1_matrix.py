def score(weights: list[int]) -> list[float]:
    total = sum(weights)
    return [sum(w * c[3 + i] for w, c in zip(weights, CRITERIA)) / (3 * total) * 100 for i in range(4)]


def main() -> None:
    assert sum(c[2] for c in CRITERIA) == 100
    lines = ["| Критерий | Вес | " + " | ".join(NAMES) + " |",
             "|---|---:|" + "---:|" * len(NAMES)]
    group = None
    for g, name, w, *s in CRITERIA:
        if g != group:
            group = g
            lines.append(f"| **{g}** | | " + " | " * (len(NAMES) - 1) + " |")
        lines.append(f"| {name} | {w} | " + " | ".join(str(x) for x in s) + " |")
    totals = score([c[2] for c in CRITERIA])
    lines.append("| **Итого, % от максимума** | **100** | " + " | ".join(f"**{t:.1f}**" for t in totals) + " |")
    (GEN / "t1_matrix.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = ["| Профиль весов | " + " | ".join(NAMES) + " | Лидер |", "|---|" + "---:|" * len(NAMES) + "---|"]
    for profile, override in PROFILES.items():
        t = score([override.get(c[1], c[2]) for c in CRITERIA])
        best = max(range(4), key=lambda i: t[i])
        lines.append(f"| {profile} | " + " | ".join(f"{x:.1f}" for x in t) + f" | {NAMES[best]} |")
    (GEN / "t1_profiles.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print((GEN / "t1_matrix.md").read_text(encoding="utf-8"))
    print((GEN / "t1_profiles.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
